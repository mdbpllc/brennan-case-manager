async function sha256(data: Uint8Array | string): Promise<string> {
  const bytes = typeof data === 'string' ? new TextEncoder().encode(data) : data;
  const buf = new Uint8Array(bytes.length);
  buf.set(bytes);
  const digest = await crypto.subtle.digest('SHA-256', buf);
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

const count = (s: string, needle: string) => s.split(needle).length - 1;

/** The new master, and the pre-edit master reconstructed from it. */
async function packages(): Promise<{
  next: ZipEntry[]; old: ZipEntry[]; nextBytes: Uint8Array; oldBytes: Uint8Array;
  xml: string; oldXml: string;
}> {
  const nextBytes = disclosuresSkeletonBytes();
  const next = await readZip(nextBytes);
  const xml = entryText(next, DOC);
  const oldXml = replaceInXml(
    replaceInXml(xml, '>{instrument_title}</w:t>', `>${HEADING_XML}</w:t>`, { expect: 1 }),
    '>{footer_title}</w:t>', `>${HEADING_XML}</w:t>`, { expect: 1 },
  );
  const old = setEntryText(next, DOC, oldXml);
  return { next, old, nextBytes, oldBytes: await writeZip(old), xml, oldXml };
}

/** FormsTab's one-client value, READ FROM ITS SOURCE rather than retyped, so
 *  the generation below renders exactly what the page would put in the tokens. */
function formsTabStaticHeading(): string {
  const m = /const MASTER_STATIC_HEADING = '([^']*)';/.exec(formsTab);
  if (!m) throw new Error('MASTER_STATIC_HEADING not found in FormsTab.tsx');
  return JSON.parse(`"${m[1]}"`) as string;
}

describe('FOS-2 B5 — the master carries the two heading tokens and nothing else changed', () => {
  it('document.xml holds {instrument_title} once, {footer_title} once, and the static heading zero times', async () => {
    const { xml } = await packages();
    expect(count(xml, '{instrument_title}')).toBe(1);
    expect(count(xml, '{footer_title}')).toBe(1);
    expect(count(xml, HEADING_XML)).toBe(0);
    expect(count(xml, 'PLAINTIFF\u2019S 194.2(b)')).toBe(0);
    // Each token is the WHOLE text of its node, in the heading's own run.
    expect(count(xml, '<w:t xml:space="preserve">{instrument_title}</w:t>')).toBe(1);
    expect(count(xml, '<w:t xml:space="preserve">{footer_title}</w:t>')).toBe(1);
    // They are the ONLY single-brace tokens in the master; the rest stay legacy.
    const canonical = parseTokens(xml).filter((t) => t.convention === 'canonical');
    expect(canonical.map((t) => t.name)).toEqual(['instrument_title', 'footer_title']);
  });

  it('puts them where the ruling put them — paragraph 39 under the caption, 83 after the certificate of service', async () => {
    const { xml } = await packages();
    const paras = paragraphTexts(xml);
    expect(paras[39]).toBe('{instrument_title}');
    expect(paras[83]).toBe('{footer_title}');
    expect(paras[37]).toBe('{{county_name_caps}} COUNTY, TEXAS');
    const cos = paras.indexOf('CERTIFICATE OF SERVICE');
    expect(cos).toBeGreaterThan(39);
    expect(cos).toBeLessThan(83);
    expect(paras[85].startsWith('194.2(b)(1)')).toBe(true);
  });

  it('the reconstructed pre-edit document.xml IS the pre-edit member, byte for byte', async () => {
    const { oldXml } = await packages();
    const bytes = new TextEncoder().encode(oldXml);
    expect(bytes.length).toBe(94056);
    expect(await sha256(bytes)).toBe(PRE_SLICE_DOCUMENT_XML_SHA256);
    expect(count(oldXml, `>${HEADING_XML}</w:t>`)).toBe(2);
  });

  it('every member of the reconstructed package is the pre-edit member, and partsDiff(old, new) is exactly word/document.xml', async () => {
    const { next, old } = await packages();
    expect(PRE_SLICE_MEMBERS).toHaveLength(26);
    expect(old.map((e) => e.name)).toEqual(PRE_SLICE_MEMBERS.map(([name]) => name));
    for (const e of old) {
      const want = PRE_SLICE_MEMBERS.find(([name]) => name === e.name)![1];
      expect(await sha256(e.data), e.name).toBe(want);
    }
    expect(partsDiff(old, next)).toEqual([DOC]);
  });

  it('word/footer1.xml is untouched — the same decompressed bytes as the pre-edit member, and still static', async () => {
    const { next, old } = await packages();
    const before = old.find((e) => e.name === 'word/footer1.xml')!.data;
    const after = next.find((e) => e.name === 'word/footer1.xml')!.data;
    expect(Array.from(after)).toEqual(Array.from(before));
    expect(await sha256(after))
      .toBe(PRE_SLICE_MEMBERS.find(([name]) => name === 'word/footer1.xml')![1]);
    const text = entryText(next, 'word/footer1.xml');
    expect(text).toContain('PLAINTIFF\u2019S TRCP 194.2(B) AND 195.5 DISCLOSURES');
    expect(parseTokens(text)).toEqual([]);
  });
});

