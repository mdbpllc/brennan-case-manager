/**
 * A generation down the FormsTab path — R17's block and narrative replace the
 * expert region — on a fixture with NO custodian-only shape and NO D-8 edge,
 * with the two heading tokens set to `heading`. Built ONCE and rendered against
 * both packages, so the only thing that differs between the two renders is the
 * skeleton.
 */
async function generationContext(heading: string): Promise<RenderContext> {
  const parties = { [ER_PARTY.id]: ER_PARTY };
  const out = await buildDesignations({
    writer: new FixtureParagraphWriter(),
    selected: [PROVIDER],
    individuals: [INDIVIDUAL],
    visits: [],
    chronologyVersions: [CHRONOLOGY],
    facilityParties: parties,
    clientName: 'Alba Quartzmoor',
    clientPronoun: 'she',
    incidentDateIso: '2025-03-14',
    caseType: 'Motor vehicle collision',
    writerInstructions: '',
  });
  expect(out.paragraphs.map((p) => p.shape)).toEqual(['treating-single']);
  expect(out.paragraphs.some((p) => p.shape === 'custodian-only')).toBe(false);

  const { context } = buildRenderContext(FIXTURE_BUNDLE, FIXTURE_ANSWERS);
  context.regions.testifying_expert = out.blocks.map((b) => blockItem(b, parties));
  context.itemSelects = { ...context.itemSelects, 'testifying_expert:0': 'treating_provider' };
  context.itemNarratives = out.itemNarratives;
  context.scalars = { ...context.scalars, instrument_title: heading, footer_title: heading };
  return context;
}

async function documentXml(r: RenderResult): Promise<string> {
  return entryText(await readZip(r.docx), DOC);
}

describe('FOS-2 B5 — a ONE-client instrument serves exactly what the pre-edit master served', () => {
  it('FormsTab resolves both tokens to the master\'s static heading on one client, and to the title on many', () => {
    expect(formsTabStaticHeading()).toBe(HEADING_TEXT);
    expect(formsTab).toContain('const heading = multiClient ? title : MASTER_STATIC_HEADING;');
    expect(formsTab).toContain('instrument_title: heading,');
    expect(formsTab).toContain('footer_title: heading,');
    // The record, the filename and the on-screen label still read `title`.
    expect(formsTab).toMatch(/ {8}title,\r?\n {8}content: rendered\.plainText,/);
    expect(formsTab).toContain('{instrumentTitle(');
    // The old note that called the second heading "the footer" is corrected.
    expect(formsTab).not.toContain('present twice (title and footer)');
    expect(formsTab).not.toContain('these resolve nothing yet');
  });

  it('renders document.xml text IDENTICAL to the reconstructed pre-edit master, and the whole .docx byte-identical', async () => {
    const { nextBytes, oldBytes } = await packages();
    const context = await generationContext(formsTabStaticHeading());

    const before = await renderInstrument(oldBytes, context);
    const after = await renderInstrument(nextBytes, context);

    expect(await documentXml(after)).toBe(await documentXml(before));
    expect(after.plainText).toBe(before.plainText);
    expect(Array.from(after.docx)).toEqual(Array.from(before.docx));
    expect(after.changedParts).toEqual([DOC]);

    // And it is the heading that is served, twice, with nothing left unresolved.
    expect(count(after.plainText, HEADING_TEXT)).toBe(2);
    expect(after.plainText).toContain('HALITE REGIONAL HOSPITAL');
    expect(after.lint.unresolvedTokens).toEqual([]);
  });

  it('the renderer fixture (one client) lints clean on the tokenized master', async () => {
    const { context } = buildRenderContext(FIXTURE_BUNDLE, FIXTURE_ANSWERS);
    expect(context.scalars.instrument_title).toBe(HEADING_TEXT);
    expect(context.scalars.footer_title).toBe(HEADING_TEXT);
    const { oldBytes } = await packages();
    const before = await renderInstrument(oldBytes, context);
    const after = await renderInstrument(disclosuresSkeletonBytes(), context);
    expect(Array.from(after.docx)).toEqual(Array.from(before.docx));
    expect(after.lint.unresolvedTokens).toEqual([]);
  });
});

