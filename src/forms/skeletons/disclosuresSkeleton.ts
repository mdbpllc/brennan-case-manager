/** Decode the bundled skeleton to bytes. Browser and Node alike. */
export function disclosuresSkeletonBytes(): Uint8Array {
  // `atob` is a global in every browser and in Node since v16, so there is no
  // Buffer fallback and therefore no Node type dependency in app code.
  const bin = atob(BASE64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}
